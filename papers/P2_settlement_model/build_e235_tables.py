"""E235 result tables for the P2 supplement (round-2 revision, Reviewer 2). 2026-10-20.

Data only, generated from experiments/E235_elevation_vs_volcanic_control/results/; captions are factual stubs for
the PI to word. Output: supplement/e235_tables_v03.tex (two tables, \\input-ready).
    python papers/P2_settlement_model/build_e235_tables.py
"""
import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
RES = HERE.parents[1] / "experiments" / "E235_elevation_vs_volcanic_control" / "results"
OUT = HERE / "supplement" / "e235_tables_v03.tex"

bands = pd.read_csv(RES / "e235_bands.csv")
out = json.loads((RES / "e235_outcome.json").read_text(encoding="utf-8"))
P = "primary_20_40"


def ci(row):
    return f"{row.delta_V_minus_N:+.3f} [{row.ci_lo:+.3f}, {row.ci_hi:+.3f}]"


m1 = bands[bands.measure.isna() & (bands.definition == P)].sort_values("band_lo_m")
d = bands[(bands.definition == P) & (bands.algorithm == "xgboost")]
rows = []
for _, b in m1.iterrows():
    if b.area_km2_V == 0 and b.area_km2_N == 0:
        continue
    lo, hi = int(b.band_lo_m), int(b.band_hi_m)
    area = lambda a: "$<$1" if 0 < a < 1 else f"{a:,.0f}"       # a sliver is not "no land"
    cells = [f"{lo:,}--{hi:,}", area(b.area_km2_V), area(b.area_km2_N), "yes" if b.usable else "no"]
    if b.usable:
        get = lambda m: d[(d.measure == m) & (d.band_lo_m == b.band_lo_m)].iloc[0]
        r, h, f = get("suit_random"), get("suit_hybrid"), get("fringe")
        cells += [f"{int(r.matched_weight_cells):,}", ci(r), ci(h), f"{f.delta_V_minus_N:+.2f} [{f.ci_lo:+.2f}, {f.ci_hi:+.2f}]"]
    else:
        cells += ["--"] * 4
    rows.append(" & ".join(cells) + r" \\")
if (m1.area_km2_N == 0).any():
    first_zero = int(m1[(m1.area_km2_N == 0)].band_lo_m.min())
    rows_note = f"No land 40 km or more from a volcanic centre lies above {first_zero:,} m."
else:
    rows_note = ""

t1 = [
    r"\begin{table}[ht]\centering\small",
    r"\caption{[S7 -- caption for the PI] Elevation bands: land within 20 km (volcanic) and 40 km or more (non-volcanic) from a volcanic centre, "
    r"and volcanic $-$ non-volcanic differences matched within band on slope, TRI and TWI (XGBoost, 10-seed ensemble maps; "
    r"95\% spatial-block bootstrap intervals). A band is compared only if each setting has at least 25~km$^2$ in at least two blocks. " + rows_note + "}",
    r"\label{tab:e235bands}",
    r"\begin{tabular}{lrrlrlll}",
    r"\toprule",
    r"Elevation (m) & Volcanic (km$^2$) & Non-volc. (km$^2$) & Compared & Matched cells & Suitability, random & Suitability, hybrid & Fringe (pp) \\",
    r"\midrule",
    *rows,
    r"\bottomrule",
    r"\end{tabular}",
    r"\end{table}",
]

defs = {"primary_20_40": r"$\leq$20 / $\geq$40 km", "sens_10_30": r"$\leq$10 / $\geq$30 km", "sens_15_30": r"$\leq$15 / $\geq$30 km"}
algos = {"xgboost": "XGBoost", "randomforest": "Random Forest", "maxent": "MaxEnt"}
rows2 = []
for dk, dl in defs.items():
    for ak, al in algos.items():
        a = out["definitions"][dk]["algorithms"][ak]["measures"]
        s = lambda m, k=1: f"{a[m]['estimate']:+.3f} [{a[m]['ci95'][0]:+.3f}, {a[m]['ci95'][1]:+.3f}]"
        fr = a["fringe"]
        rows2.append(" & ".join([dl, al, s("suit_random"), s("suit_hybrid"),
                                 out["definitions"][dk]["algorithms"][ak]["M2_summary"].replace("NOT SPECIFIC", "not specific").replace("INCONCLUSIVE", "inconclusive").replace("SPECIFIC", "specific"),
                                 f"{fr['estimate']:+.2f} [{fr['ci95'][0]:+.2f}, {fr['ci95'][1]:+.2f}]",
                                 fr["verdict"].lower()]) + r" \\")
        dl = ""
t2 = [
    r"\begin{table}[ht]\centering\small",
    r"\caption{[S8 -- caption for the PI] Pooled volcanic $-$ non-volcanic differences over the compared bands, by zone definition and algorithm, "
    r"with the verdicts of the pre-registered rules (threshold 0.05 suitability; 5 percentage points for the fringe; "
    r"the suitability verdict is the one shared by at least two of the three background designs).}",
    r"\label{tab:e235summary}",
    r"\begin{tabular}{llllll l}",
    r"\toprule",
    r"Zones (V / N) & Algorithm & Suitability, random & Suitability, hybrid & Verdict & Fringe (pp) & Verdict \\",
    r"\midrule",
    *rows2,
    r"\bottomrule",
    r"\end{tabular}",
    r"\end{table}",
]
OUT.parent.mkdir(exist_ok=True)
OUT.write_text("% Generated by build_e235_tables.py from E235 results -- do not edit numbers by hand.\n"
               + "\n".join(t1) + "\n\n" + "\n".join(t2) + "\n", encoding="utf-8")
print(f"wrote {OUT} ({len(rows)} band rows, {len(rows2)} summary rows)")
