def write_register(entries, output_path):
    """Write entries to CSV."""
    fieldnames = [
        "source", "year_report", "site_name", "modern_name",
        "location", "regency", "province", "lat", "lon",
        "built_ce", "found_year", "burial_depth_m", "depth_type",
        "material", "volcanic_system", "volcano_dist_km",
        "rate_mm_yr", "condition", "context", "notes", "ov_page"
    ]

    with open(output_path, 'w', encoding='utf-8', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for entry in entries:
            writer.writerow(entry)

    return len(entries)


def summarize(entries):
    """Print register summary statistics."""
    print("=" * 70)
    print("COLONIAL ARCHAEOLOGICAL REGISTER — SUMMARY")
    print("=" * 70)

    n = len(entries)
    with_depth = [e for e in entries if e.get("burial_depth_m") and e["burial_depth_m"] != ""]
    with_coords = [e for e in entries if e.get("lat") and e["lat"] != ""]
    with_volcanic = [e for e in entries if e.get("volcanic_system") and "unknown" not in str(e.get("volcanic_system", "")).lower() and e.get("volcanic_system") != ""]
    provinces = set(e.get("province", "unknown") for e in entries if e.get("province"))
    sources = set(e.get("source", "") for e in entries)

    print(f"\nTotal entries:           {n}")
    print(f"With depth measurement:  {len(with_depth)}")
    print(f"With coordinates:        {len(with_coords)}")
    print(f"With volcanic system:    {len(with_volcanic)}")
    print(f"Provinces covered:       {len(provinces)} — {', '.join(sorted(provinces))}")
    print(f"OV volumes used:         {len(sources)} — {', '.join(sorted(sources))}")

    if with_depth:
        depths = [float(e["burial_depth_m"]) for e in with_depth if float(e["burial_depth_m"]) > 0]
        if depths:
            print(f"\nDepth statistics (n={len(depths)}):")
            print(f"  Min:    {min(depths):.2f} m")
            print(f"  Max:    {max(depths):.2f} m")
            print(f"  Mean:   {sum(depths)/len(depths):.2f} m")
            print(f"  Median: {sorted(depths)[len(depths)//2]:.2f} m")

    print(f"\nCondition breakdown:")
    conditions = {}
    for e in entries:
        c = e.get("condition", "unknown")
        conditions[c] = conditions.get(c, 0) + 1
    for c, count in sorted(conditions.items(), key=lambda x: -x[1]):
        print(f"  {c:20s}: {count}")

    print(f"\nContext breakdown:")
    contexts = {}
    for e in entries:
        c = e.get("context", "unknown")
        contexts[c] = contexts.get(c, 0) + 1
    for c, count in sorted(contexts.items(), key=lambda x: -x[1]):
        print(f"  {c:25s}: {count}")


